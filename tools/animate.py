        al = caps[i][1] * min(1.0, tin / 0.4, (part - tin) / 0.4 if i < len(caps) - 1 else 1.0)
        img = img * (1 - al) + caps[i][0] * al
        img = img * (1 - sh['lab'][1]) + sh['lab'][0] * sh['lab'][1]
        return np.clip(img * ease(fade), 0, 255).astype(np.uint8)

