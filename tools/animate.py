# A shot's layers are outlines in fractions of the cropped frame; whatever lies outside them stays still.
# move(name, u, sec, pose, w, h) places a layer: u runs 0 to 1 through the shot, sec is seconds, pose counts poses.

def m_orni(n, u, sec, pose, w, h):
    hub = (.455 * w, .50 * h); bob = 9 * math.sin(sec * 2.2) + 4 * math.sin(sec * 5.1); grow = 0.84 + 0.22 * ease(u)
    if n == 'rotor': return affine(hub, dy=bob, angle=2.2 if pose % 2 == 0 else -2.2, sx=grow * (1.0 if pose % 2 == 0 else 0.86), sy=grow)
    return affine(hub, dy=bob, angle=1.5 * math.sin(sec * 1.7), sx=grow)


def m_dive(n, u, sec, pose, w, h):
    if n == 'orni': return affine((.70 * w, .37 * h), dx=120 * ease(u * 1.3), dy=-60 * ease(u * 1.3) + 7 * math.sin(sec * 2.6), angle=-3 * ease(u), sx=1.0 if pose % 2 == 0 else 0.9, sy=1.0)
    return affine((.08 * w, .95 * h), angle=1.5 * ease(u), sx=1 - 0.15 * ease(u))


def b_dive(n, a, u, sec):
    if n != 'worm': return a
    h, w = a.shape; yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    return cv2.remap(a, xx, yy + 12 * np.clip(xx / (0.6 * w), 0, 1) ** 1.5 * np.sin(xx / w * 9.0 - sec * 3.2), cv2.INTER_LINEAR, borderValue=0)


def m_rise(n, u, sec, pose, w, h):
    if n == 'worm':
        up = ease(min(1.0, u / 0.5))
        return affine((.60 * w, .98 * h), angle=-9 + 9 * up + 3.5 * math.sin(sec * 1.4) * up, sx=0.72 + 0.28 * up, sy=0.10 + 0.90 * up)
    return affine((.80 * w, .55 * h), dx=7 * math.cos(sec * 1.5), dy=6 * math.sin(sec * 2.3), angle=5 * math.sin(sec * 1.5))


def m_accel(n, u, sec, pose, w, h):
    if n == 'worm': return affine((.55 * w, .42 * h), dx=(0.10 - 0.16 * u * u) * w, dy=3 * math.sin(sec * 3))
    return affine((.2 * w, .68 * h), dx=-18 * ease(u), dy=6 * math.sin(sec * 2.4), angle=3 * math.sin(sec * 1.3), sx=1.0 if pose % 2 == 0 else 0.93, sy=1.0)


def b_accel(n, a, u, sec):
    if n != 'worm': return a
    h, w = a.shape; yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    return cv2.remap(a, xx, yy + 7 * np.sin(xx / w * 14.0 + sec * 5.0), cv2.INTER_LINEAR, borderValue=0)


def m_refuse(n, u, sec, pose, w, h):
    if n == 'orni': return affine((.77 * w, .2 * h), dx=(0.10 - 0.22 * ease(u)) * w, dy=8 * math.sin(sec * 2.5), sx=1.0 if pose % 2 == 0 else 0.9, sy=1.0)
    return affine((.5 * w, .8 * h), dy=-5 * step(pose + (0 if n == 'men1' else 2)), angle=(1.6 if n == 'men1' else -1.6) * math.sin(pose * math.pi / 3))


def m_wing(n, u, sec, pose, w, h):
    return affine((.43 * w, .48 * h), dy=5 * math.sin(sec * 2), sx=0.7 + 1.7 * u * u)


def m_boom(n, u, sec, pose, w, h):
    burst = 0.15 + 0.93 * ease(sec / 0.3) + 0.10 * u
    return affine((.5 * w, .5 * h), angle=2.5 * math.sin(pose * 2.1) * (1 - u), sx=burst)


def fx_boom(u, sec, pose):
    k = max(0.0, 1 - sec / 1.4)
    return dict(shake=(22 * k * math.sin(pose * 2.7), 16 * k * math.cos(pose * 3.9)), flash=max(0.0, 1 - sec / 0.45), invert=sec < 0.17)


def m_land(n, u, sec, pose, w, h):
    if n == 'craft2': k = 1 - ease(u / 0.6); return affine((.6 * w, .85 * h), dx=.24 * w * k, dy=-.42 * h * k * k, angle=-9 * k)
    if n == 'craft1': k = 1 - span(u, 0.2, 0.85); return affine((.4 * w, .86 * h), dx=.3 * w * k, dy=-.5 * h * k * k, angle=-9 * k)
    return affine((.8 * w, .85 * h), sx=0.55 + 0.45 * span(u, 0.3, 1.0), dy=2 * math.sin(sec * 2))


def m_run(n, u, sec, pose, w, h):
    return affine((.1 * w, .9 * h), dx=(-0.13 + 0.17 * u) * w, dy=-7 * step(pose))


def m_duke(n, u, sec, pose, w, h):
    hub = (.455 * w, .46 * h); dy = (-0.22 + 0.27 * ease(u)) * h + 5 * math.sin(sec * 2.3)
    if n == 'rotor': return affine(hub, dy=dy, angle=2.0 if pose % 2 == 0 else -2.0, sx=1.0 if pose % 2 == 0 else 0.88, sy=1.0)
    return affine(hub, dy=dy, angle=1.2 * math.sin(sec * 1.9))


def m_menrun(n, u, sec, pose, w, h):
    if n == 'left': return affine((.1 * w, .95 * h), dx=(-0.14 + 0.17 * u) * w, dy=-12 * step(pose), angle=2 * math.sin(pose * math.pi / 4))
    return affine((.72 * w, .95 * h), dx=(0.13 - 0.16 * u) * w, dy=-14 * step(pose + 2), angle=-2 * math.sin(pose * math.pi / 4))


def m_throw(n, u, sec, pose, w, h):
    k = (u * 2) % 1.0                                  # thrown twice
    return affine((.76 * w, .36 * h), dx=(-0.14 + 0.24 * k) * w, dy=(-0.06 + 0.5 * k * k) * h, angle=-40 + 140 * k, sx=0.75 + 0.3 * k)


def m_takeoff(n, u, sec, pose, w, h):
    if n == 'worm': return affine((.8 * w, .79 * h), dx=(0.16 - 0.19 * ease(u)) * w, sx=0.72 + 0.4 * ease(u), dy=3 * math.sin(sec * 4))
    if n == 'far': return affine((.59 * w, .6 * h), dx=10 * math.cos(sec * 1.7), dy=-30 * u + 5 * math.sin(sec * 2.5))
    return affine((.25 * w, .6 * h), dx=3 * math.sin(pose * 2.3), dy=-0.035 * h * span(u, 0.55, 1.0) + 3 * math.cos(pose * 3.1))


def fx_takeoff(u, sec, pose):
    k = span(u, 0.5, 1.0)
    return dict(shake=(5 * k * math.sin(pose * 2.7), 4 * k * math.cos(pose * 3.9)), flash=0.0)


