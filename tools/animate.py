"""Cut-out animation from the storyboard: 'The worm, animated' (scene 60).

Nothing is drawn or generated by a model. For each shot the dark lines of one storyboard frame are lifted off its
paper, divided into parts by hand-set outlines (the ornithopter, the worm, the running men), and each part is
moved, turned, scaled or bent over time. It moves on twos, a new pose every second frame, with a slight wobble of
the line, as cut-outs under a rostrum camera would. The last shot does the same with a colour drawing from the
illustrated screenplay; there, the paper behind the part that moves is filled in from its surroundings.

The words under the pictures are fetched from assets/script.js, so they are the screenplay's as typed.
The sound effects (wind, rotor, the worm, the explosion) are synthesized here from noise and sine waves.

usage: animate.py <fonts dir> <out dir> [--debug]
  writes <out>/wormanim-silent.mp4, <out>/wormanim-sfx.wav and <out>/wormanim-cues.json (for tools/record_score.js)
  --debug writes one sheet of layer outlines and four poses per shot instead, to check an edit quickly
"""
