def ease(x):
    x = min(1.0, max(0.0, x)); return x * x * (3 - 2 * x)


def span(u, a, b):
    """0 before a, 1 after b, eased between."""
    return ease((u - a) / (b - a))


# ------------------------------------------------------------------ picture ----

def ink_of(name, crop=None, lo=0.10, width=0.42):
    """A frame's ink as an alpha (0 paper, 1 ink), scaled up to cover the picture window with a margin."""
    import film_scene as fs
    g = cv2.imread(os.path.join(REPO, 'frames', name + '.webp'), cv2.IMREAD_GRAYSCALE)
    l, t, r, b = crop or [int(v) for v in fs.inner(g)]
    g = g[t:b, l:r].astype(np.float32)
    paper = np.percentile(g, 92)
    a = np.clip((paper - g) / max(1.0, paper - 25.0), 0, 1)
    s = max(PW / a.shape[1], PH / a.shape[0]) * 1.08
    a = cv2.resize(a, (int(a.shape[1] * s), int(a.shape[0] * s)), interpolation=cv2.INTER_LANCZOS4)
    a = np.clip((a - lo) / width, 0, 1)
    return a * a * (3 - 2 * a)                     # lose paper tone and scan smudge, keep the line


def poly_mask(shape, polys, feather=9):
    h, w = shape; m = np.zeros((h, w), np.float32)
    if isinstance(polys[0][0], (int, float)): polys = [polys]
    for pts in polys: cv2.fillPoly(m, [np.array([[int(x * w), int(y * h)] for x, y in pts], np.int32)], 1.0)
    return cv2.GaussianBlur(m, (0, 0), feather)


def box(x0, y0, x1, y1):
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]


def affine(pivot, dx=0.0, dy=0.0, angle=0.0, sx=1.0, sy=None):
    sy = sx if sy is None else sy
    px, py = pivot; c, s = math.cos(math.radians(angle)), math.sin(math.radians(angle))
    A = np.array([[c * sx, -s * sy], [s * sx, c * sy]], np.float32)
    t = np.array([px + dx, py + dy], np.float32) - A @ np.array([px, py], np.float32)
    return np.hstack([A, t[:, None]]).astype(np.float32)


def warp(a, M, border=0):
    return cv2.warpAffine(a, M, (a.shape[1], a.shape[0]), flags=cv2.INTER_LINEAR, borderValue=border)


BOIL = {}


def boil(a, pose, amp=1.3):
    """The slight wobble of a line redrawn for every pose: one of four small, smooth displacements."""
    h, w = a.shape[:2]; k = (pose % 4, h, w, amp)
    if k not in BOIL:
        f = [cv2.resize(rng.normal(0, 1, (h // 90 + 2, w // 90 + 2)).astype(np.float32), (w, h), interpolation=cv2.INTER_CUBIC) for _ in range(2)]
        yy, xx = np.mgrid[0:h, 0:w].astype(np.float32); BOIL[k] = (xx + f[0] * amp, yy + f[1] * amp)
    return cv2.remap(a, BOIL[k][0], BOIL[k][1], cv2.INTER_LINEAR, borderValue=0)


def step(pose):
    """The up and down of a run, a new footfall every fourth pose."""
    return abs(math.sin(pose * math.pi / 4))


