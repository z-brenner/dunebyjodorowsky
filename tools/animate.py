class Swallow:
    """The screenplay's drawing of the worm at the harvester: the harvester leans and sinks, the teeth turn, the camera closes on the mouth."""

    def __init__(self):
        im = cv2.imread(os.path.join(REPO, 'art', '060.webp')); h, w = im.shape[:2]
        im = im[int(.02 * h):int(.955 * h), int(.012 * w):int(.99 * w)]
        s = 2400 / im.shape[1]; self.im = cv2.resize(im, (2400, int(im.shape[0] * s)), interpolation=cv2.INTER_LANCZOS4).astype(np.float32)
        self.h, self.w = self.im.shape[:2]; sh = (self.h, self.w)
        hv = poly_mask(sh, [(.075, .715), (.30, .715), (.315, .80), (.315, .95), (.075, .95)], 5)
        hole = (poly_mask(sh, [(.065, .70), (.31, .70), (.325, .80), (.325, .955), (.065, .955)], 1) > 0.5).astype(np.uint8) * 255
        small = cv2.resize(self.im.astype(np.uint8), (self.w // 2, self.h // 2)); hs = cv2.resize(hole, (self.w // 2, self.h // 2))
        self.back = cv2.resize(cv2.inpaint(small, hs, 9, cv2.INPAINT_TELEA), (self.w, self.h)).astype(np.float32)      # the paper behind the harvester
        self.back = self.im * (1 - cv2.GaussianBlur(hole.astype(np.float32) / 255, (0, 0), 6)[:, :, None]) + self.back * cv2.GaussianBlur(hole.astype(np.float32) / 255, (0, 0), 6)[:, :, None]
        self.hv = np.dstack([self.im * hv[:, :, None], hv])
        fr = poly_mask(sh, [(.30, .80), (.50, .74), (.50, 1.0), (0, 1.0), (0, .945), (.30, .945)], 5)
        self.front = np.dstack([self.im * fr[:, :, None], fr])
        yy, xx = np.mgrid[0:self.h, 0:self.w].astype(np.float32); self.c = (.365 * self.w, .295 * self.h)
        self.disc = np.clip((225 - np.hypot(xx - self.c[0], yy - self.c[1])) / 26, 0, 1)

    def picture(self, u, sec, pose):
        img = self.back.copy()
        lean = span(u, 0.08, 0.36); sink = span(u, 0.36, 0.74)
        M = affine((.30 * self.w, .93 * self.h), dx=.02 * self.w * sink, dy=.30 * self.h * sink * sink + 3 * math.sin(pose * 2.1) * lean, angle=17 * lean + 10 * sink)
        hv = warp(self.hv, M); a = hv[:, :, 3:4]; img = img * (1 - a) + hv[:, :, :3]
        a = self.front[:, :, 3:4]; img = img * (1 - a) + self.front[:, :, :3]
        turn = warp(self.im, affine(self.c, angle=9 * math.sin(sec * 2.1) + 14 * span(u, 0.3, 1.0))); d = self.disc[:, :, None]
        img = img * (1 - d) + turn * d
        k = span(u, 0.42, 0.95)                         # the camera closes on the mouth
        x, y, ww = 0.0 + 0.13 * k, 0.30 - 0.245 * k, 1.0 - 0.50 * k
        shake = span(u, 0.3, 0.5) * (1 - span(u, 0.8, 1.0))
        x0 = x * self.w + 7 * shake * math.sin(pose * 2.7); y0 = y * self.h + 6 * shake * math.cos(pose * 3.9)
        cw = ww * self.w; ch = cw * PH / PW
        x0 = min(max(0, x0), self.w - cw); y0 = min(max(0, y0), self.h - ch)
        Mw = np.array([[PW / cw, 0, -x0 * PW / cw], [0, PH / ch, -y0 * PH / ch]], np.float32)
        return cv2.warpAffine(img, Mw, (PW, PH), flags=cv2.INTER_LINEAR)


def text_layer(lines, fonts):
    """Lines of (speaker or None, text) set under the picture, as in the other films."""
    im = Image.new('RGBA', (W, H), (0, 0, 0, 0)); d = ImageDraw.Draw(im); y = PY + PH + 30
    f = ImageFont.truetype(os.path.join(fonts, 'CourierPrime.ttf'), 34); fb = ImageFont.truetype(os.path.join(fonts, 'CourierPrime-Bold.ttf'), 24)
    for who, text in lines:
        if who: d.text(((W - d.textlength(who.upper(), font=fb)) / 2, y - 8), who.upper(), font=fb, fill=GOLD + (255,)); y += 26
        words, row = text.replace("'", '’').split(), ''
        rows = []
        for wd in words:
            if d.textlength(row + ' ' + wd, font=f) > 1380 and row: rows.append(row); row = wd
            else: row = (row + ' ' + wd).strip()
        rows.append(row)
        for r in rows: d.text(((W - d.textlength(r, font=f)) / 2, y), r, font=f, fill=TXT + (255,)); y += 44
    a = np.asarray(im).astype(np.float32); return a[:, :, 2::-1], a[:, :, 3:4] / 255.0


